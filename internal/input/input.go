// Package input — вход сборщика: откуда берутся записи, когда источник не файл.
//
// Сборщик (internal/collector) делится на две половины. Доставка одна на всех:
// номера записей, дисковый буфер, отправка пачками, обещания хранилища, пульс,
// свидетель голов. Вход — то, что эту доставку кормит. Файлы сборщик читает сам
// (это его исходный вход, и он остаётся в его пакете); всё остальное — база,
// очередь, чужой журнал — приходит через Input.
//
// Новый вход — это тип с методами Input и строка в collector.newInput. Про
// номера, буфер, повторы и хранилище ему знать не нужно: он отдаёт тела записей
// в Sink и говорит, где остановился.
//
// МЕСТО (cursor). Вход сам решает, что значит его место: позиция в журнале
// базы, смещение в очереди. Сборщик хранит это число в буфере в той же записи,
// что и тело, одним fsync: после падения вход получает ровно то место, до
// которого его записи легли на диск, и не выдаст одно событие дважды под
// разными номерами.
package input

import (
	"context"
	"time"
)

// Sink — буфер сборщика глазами входа.
type Sink interface {
	// Emit кладёт записи в буфер и возвращается после fsync. Записи получают
	// номера подряд; first — номер первой. cursor — место входа после последней
	// записи пачки; с остальными записями пачки в буфер ложится прежнее место
	// (пачка может лечь на диск не вся — тогда место не сдвинется, и вход
	// получит её заново). Тело — не длиннее предела записи хранилища
	// (evidence.MaxBodyLen): резать его на куски должен сам вход.
	Emit(bodies [][]byte, cursor uint64) (first uint64, err error)
	// Next — номер, который получит следующая запись.
	Next() uint64
	// Gap — вход потерял данные и знает об этом (источник стёр непрочитанное):
	// сборщик пропускает номер, и хранилище запишет в цепь пропуск. Потеря
	// видна, а не тиха.
	Gap(why string) error
}

// Input — вход сборщика. Все методы зовутся из одного цикла сборщика, по
// очереди.
type Input interface {
	// Open — один раз, до первого чтения. cursor — место, которое легло в буфер
	// с последней записью этого входа; 0 — записей ещё не было.
	Open(cursor uint64, sink Sink) error
	// Read — один проход без ожидания: всё, что вход уже получил, — в буфер.
	// n — сколько записей легло. Источник недоступен — не ошибка: вход сам
	// говорит об этом в журнал и пробует снова в следующий проход, а сборщик
	// тем временем шлёт накопленное и пульс. Ошибка — когда отказал буфер.
	Read() (n int, err error)
	// ReadAll — для escollect -once: всё, что было у источника к моменту
	// вызова. Здесь недоступный источник — ошибка.
	ReadAll(ctx context.Context) (n int, err error)
	// Wait ждёт, пока появится что читать, но не дольше d.
	Wait(ctx context.Context, d time.Duration)
	Close() error
}
